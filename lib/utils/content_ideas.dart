/// Идея контента: заголовок, структура (пар «блок → описание»), теги.
class ContentIdea {
  final String title;
  final List<(String, String)> structure;
  final List<String> tags;

  const ContentIdea({
    required this.title,
    required this.structure,
    required this.tags,
  });

  String get fullText {
    final buf = StringBuffer();
    buf.writeln(title);
    buf.writeln();
    for (final p in structure) {
      buf.writeln('${p.$1}: ${p.$2}');
    }
    if (tags.isNotEmpty) {
      buf.writeln();
      buf.writeln(tags.map((t) => '#$t').join(' '));
    }
    return buf.toString();
  }
}

