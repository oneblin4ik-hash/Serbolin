/// При необходимости можно добавить плейсхолдеры вида `{name}` и заменять
/// их перед возвратом.
class _IdeaTemplate {
  final String title;
  final List<(String, String)> structure;
  final List<String> tags;

  _IdeaTemplate({
    required this.title,
    required this.structure,
    required this.tags,
  });

  ContentIdea build() {
    return ContentIdea(
      title: title,
      structure: List<(String, String)>.from(structure),
      tags: List<String>.from(tags),
    );
  }
}
